"""Validate the diagram registry and compile its independent visual regression gallery."""
import argparse
import json
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
FIG = ROOT / 'course-study/figures'

def validate():
    items = json.loads((FIG / 'catalog.json').read_text(encoding='utf-8'))
    ids = [item['id'] for item in items]
    if len(ids) != len(set(ids)):
        raise SystemExit('Duplicate catalog identifier')
    modules = sorted((FIG / 'modules').glob('*.tex'))
    definitions = []
    for p in modules:
        definitions += re.findall(r'\\DGDeclareDiagram\{([a-z0-9-]+)\}', p.read_text(encoding='utf-8'))
    if len(definitions) != len(set(definitions)) or set(ids) != set(definitions):
        raise SystemExit('Catalog and module definitions differ')
    for name in ids:
        p = FIG / (name + '.tex')
        if not p.is_file() or not re.search(r'\\DGDiagram(?:\[[^\]]*\])?\{' + re.escape(name) + r'\}', p.read_text(encoding='utf-8')):
            raise SystemExit(f'Missing/default wrapper mismatch: {name}')
    for p in (ROOT / 'course-study').rglob('*.tex'):
        s = p.read_text(encoding='utf-8')
        for name in re.findall(r'\\DGDiagram(?:\[[^\]]*\])?\{([a-z0-9-]+)\}', s):
            if name not in ids:
                raise SystemExit(f'Unknown diagram {name} in {p.relative_to(ROOT)}')
    print(f'OK: {len(ids)} diagrams, {len(modules)} modules; registry/wrappers consistent.')
    return items

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check-only', action='store_true')
    args = parser.parse_args()
    items = validate()
    if args.check_only:
        return
    if not shutil.which('latexmk'):
        raise SystemExit('latexmk is required; install TeX Live and add it to PATH.')
    out = ROOT / 'build'
    out.mkdir(exist_ok=True)
    header = r'''% Generated by scripts/build-figures.py; edit the modules, not this file.
\documentclass[UTF8,11pt,a5paper,landscape]{ctexart}
\usepackage[margin=14mm]{geometry}
\usepackage{hyperref}
\newcommand{\dd}{\mathrm{d}}
\input{course-study/figures/dg-diagrams}
\hypersetup{pdftitle={微分几何TikZ模块图册},pdfauthor={学习整理工程}}
\pagestyle{plain}
\newcommand{\DGGalleryPage}[4]{%
 \section*{#2}\noindent\texttt{#1}\par\medskip
 \begin{center}#4\end{center}\medskip\noindent #3\clearpage}
\begin{document}
'''
    body = []
    for item in items:
        name = item['id']
        body.append(r'\DGGalleryPage{' + name + '}{' + item['title'] + '}{' + item['provenance'] + '}{'
                    + r'\input{course-study/figures/' + name + '}}\n')
    variants = [
        ('polar-tangent', r'/dg/polar radius=1.4,/dg/polar angle=30', '极坐标参数变化'),
        ('frenet-circle', r'/dg/circle radius=1.2', '圆半径参数变化'),
        ('stereographic', r'/dg/stereo angle=20,scale=1.4', '立体投影点变化'),
        ('osculating-parabola', r'/dg/parabola curvature=1.25', '曲率及密切圆半径变化'),
        ('compact-cover', r'/dg/compact intervals=4', '有限子覆盖成员数量变化'),
    ]
    for name, keys, title in variants:
        body.append(r'\DGGalleryPage{' + name + '}{' + title + '}{'
                    + r'\texttt{\detokenize{' + keys + '}}}{'
                    + r'\DGDiagram[' + keys + ']{' + name + '}}\n')
    # Compile-time assertion: options must not leak out of a call's group.
    trailer = r'''
\ifdim\DGPolarRadius pt=2pt\else\errmessage{DG radius parameter leaked}\fi
\ifdim\DGPolarAngle pt=0pt\else\errmessage{DG angle parameter leaked}\fi
\ifdim\DGCircleRadius pt=1.65pt\else\errmessage{DG circle parameter leaked}\fi
\ifdim\DGStereoAngle pt=36.8699pt\else\errmessage{DG stereo parameter leaked}\fi
\ifdim\DGParabolaCurvature pt=1pt\else\errmessage{DG curvature parameter leaked}\fi
\ifnum\DGCompactIntervals=3\else\errmessage{DG cover parameter leaked}\fi
\typeout{DG-PARAMETER-ISOLATION: PASS}
\end{document}
'''
    source = out / 'figures-gallery.tex'
    source.write_text(header + ''.join(body) + trailer, encoding='utf-8')
    log = out / 'figures-gallery-console.txt'
    with log.open('w', encoding='utf-8') as stream:
        completed = subprocess.run([
            'latexmk', '-xelatex', '-interaction=nonstopmode', '-halt-on-error',
            '-file-line-error', '-outdir=build', str(source.relative_to(ROOT))
        ], cwd=ROOT, stdout=stream, stderr=subprocess.STDOUT)
    if completed.returncode:
        raise SystemExit(f'Gallery build failed; see {log}')
    texlog = (out / 'figures-gallery.log').read_text(encoding='utf-8', errors='replace')
    findings = re.findall(r'^.*(?:Warning:|Overfull|Underfull|Missing character:).*$', texlog, re.M)
    if findings:
        raise SystemExit('Gallery needs review:\n' + '\n'.join(findings))
    if 'DG-PARAMETER-ISOLATION: PASS' not in texlog:
        raise SystemExit('Parameter isolation check did not finish')
    print(f'PDF: {out / "figures-gallery.pdf"} ({len(items)} defaults + {len(variants)} variants)')

if __name__ == '__main__':
    main()
